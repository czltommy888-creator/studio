import assert from 'node:assert/strict'
import {existsSync,mkdirSync} from 'node:fs'
import {chromium} from 'playwright-core'
const executablePath=process.env.CHROME_PATH || ['C:/Program Files/Google/Chrome/Application/chrome.exe','C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'].find(existsSync)
const browser=await chromium.launch({executablePath,headless:true})
const url=process.argv[2]||'http://127.0.0.1:4173'
const issues=[]
mkdirSync('screenshots',{recursive:true})
const page=await browser.newPage({viewport:{width:1500,height:950},reducedMotion:'reduce'})
page.on('pageerror',e=>issues.push(String(e)))
page.on('console',m=>{if(m.type()==='error')issues.push(m.text())})
page.on('response',r=>{if(r.status()>=400)issues.push(r.url())})
async function readyImage(locator){await locator.evaluate(el=>el.decode())}
try {
 assert.equal((await page.goto(url)).status(),200)
 await readyImage(page.locator('.hero-image img'))
 await page.screenshot({path:'screenshots/home-desktop.png'})
 for(const title of ['Evening Road','After Hours','Crossing Paths','Between Us','Parallel Lines']){
   assert.equal(await page.locator('.cover-title').innerText(),title)
   await readyImage(page.locator('.hero-image img'))
   await page.getByRole('button',{name:'Next featured photograph'}).click()
 }
 assert.equal(await page.locator('.cover-title').innerText(),'Evening Road')
 await page.locator('.explore').click()
 await page.locator('.gallery figure').first().scrollIntoViewIfNeeded()
 await readyImage(page.locator('.gallery img').first())
 await page.waitForFunction(()=>Number(getComputedStyle(document.querySelector('figure')).opacity)>.99)
 await page.screenshot({path:'screenshots/selected-works.png'})
 await page.locator('.filters button').filter({hasText:/^portrait/i}).click()
 assert.equal(await page.locator('figure').count(),2)
 await page.locator('[data-view]').first().click()
 await readyImage(page.locator('dialog img'))
 await page.keyboard.press('ArrowRight')
 assert.equal(await page.locator('dialog h3').innerText(),'Between Us')
 await page.keyboard.press('ArrowLeft')
 await readyImage(page.locator('dialog img'))
 await page.screenshot({path:'screenshots/photo-viewer.png'})
 await page.keyboard.press('Escape')
 assert.equal(await page.locator('dialog').count(),0)
 await page.setViewportSize({width:390,height:844})
 await page.goto(url)
 await readyImage(page.locator('.hero-image img'))
 await page.screenshot({path:'screenshots/home-mobile.png'})
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.locator('.menu').click()
 await page.locator('nav a[href="#works"]').click()
 const nextTitle=await page.locator('figcaption h3').nth(1).innerText()
 await page.locator('[data-view]').first().click()
 const touch=await page.context().newCDPSession(page)
 await touch.send('Emulation.setTouchEmulationEnabled',{enabled:true})
 await touch.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:300,y:250}]})
 await touch.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:70,y:245}]})
 await touch.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]})
 assert.equal(await page.locator('dialog h3').innerText(),nextTitle)
 await page.getByLabel('Close viewer').click()
 await page.locator('summary').click()
 await page.getByLabel('Your enquiry').fill('Photography enquiry')
 const downloaded=page.waitForEvent('download')
 await page.getByText('Download draft',{exact:true}).click()
 assert.equal((await downloaded).suggestedFilename(),'chen-studio-enquiry.txt')
 assert.deepEqual(issues,[])
 console.log('Verified desktop, mobile, viewer, filters, download and console. Four screenshots saved.')
}finally{await browser.close()}

